-- =====================================================
-- SISTEMA DE GERENCIAMENTO DE LAR DE IDOSOS
-- Script 02: Criação das Tabelas e Constraints
-- =====================================================

CREATE TYPE tipo_movimentacao AS ENUM ('entrada', 'saida');
-- =====================================================================
-- 1. TABELAS BASE
-- =====================================================================

CREATE TABLE endereco (
    id_endereco int4 GENERATED BY DEFAULT AS IDENTITY,
    rua varchar(255) NOT NULL,
    numero int4 NOT NULL,
    bairro varchar(255) NOT NULL,
    cidade varchar(255) NOT NULL,
    complemento varchar(255),

    CONSTRAINT endereco_pkey PRIMARY KEY (id_endereco)
);

CREATE TABLE especialidade (
    id_especialidade int4 GENERATED BY DEFAULT AS IDENTITY,
    nome_especialidade varchar(255) NOT NULL UNIQUE,
    descricao text,

    CONSTRAINT especialidade_pkey PRIMARY KEY (id_especialidade)
);

CREATE TABLE medicamento (
    id_medicamento int4 GENERATED BY DEFAULT AS IDENTITY,
    nome_medicamento varchar(255) NOT NULL,
    dosagem varchar(50) NOT NULL,
    via_administracao varchar(50) NOT NULL,

    CONSTRAINT medicamento_pkey PRIMARY KEY (id_medicamento)
);

-- =====================================================================
-- 2. TABELAS COM DEPENDÊNCIAS DIRETAS
-- =====================================================================

CREATE TABLE pessoa (
    id_pessoa int4 GENERATED BY DEFAULT AS IDENTITY,
    nome_pessoa varchar(225) NOT NULL,
    cpf varchar(30) NOT NULL UNIQUE,
    telefone varchar(20),
    data_nascimento date NOT NULL,
    data_entrada timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_endereco int4 NOT NULL,

    CONSTRAINT pessoa_pkey PRIMARY KEY (id_pessoa),

    CONSTRAINT fk_pessoa_endereco
        FOREIGN KEY (id_endereco)
        REFERENCES endereco(id_endereco)
        ON DELETE RESTRICT
);

CREATE TABLE lar (
    id_lar int4 GENERATED BY DEFAULT AS IDENTITY,
    nome varchar(255) NOT NULL,
    cnpj varchar(18) NOT NULL UNIQUE,
    id_endereco int4 NOT NULL,

    CONSTRAINT lar_pkey PRIMARY KEY (id_lar),

    CONSTRAINT fk_lar_endereco
        FOREIGN KEY (id_endereco)
        REFERENCES endereco(id_endereco)
        ON DELETE RESTRICT
);

-- =====================================================================
-- 3. FUNCIONÁRIOS, IDOSOS E ESTOQUE
-- =====================================================================

CREATE TABLE funcionario (
    id_funcionario int4 GENERATED BY DEFAULT AS IDENTITY,
    id_pessoa int4 NOT NULL UNIQUE,
    id_especialidade int4 NOT NULL,
    funcao varchar(100) NOT NULL,
    data_contratacao date NOT NULL,
    salario decimal(10,2) NOT NULL,
    status varchar(50) NOT NULL,
    data_desligamento date,

    CONSTRAINT funcionario_pkey PRIMARY KEY (id_funcionario),

    CONSTRAINT fk_funcionario_pessoa
        FOREIGN KEY (id_pessoa)
        REFERENCES pessoa(id_pessoa)
        ON DELETE CASCADE,

    CONSTRAINT fk_funcionario_especialidade
        FOREIGN KEY (id_especialidade)
        REFERENCES especialidade(id_especialidade)
        ON DELETE RESTRICT
);

CREATE TABLE idoso (
    id_idoso int4 GENERATED BY DEFAULT AS IDENTITY,
    numero_quarto int4 NOT NULL,
    restricoes_medicas text,
    observacoes text,
    id_pessoa int4 NOT NULL UNIQUE,
    id_lar int4 NOT NULL,

    CONSTRAINT idoso_pkey PRIMARY KEY (id_idoso),

    CONSTRAINT fk_idoso_pessoa
        FOREIGN KEY (id_pessoa)
        REFERENCES pessoa(id_pessoa)
        ON DELETE CASCADE,

    CONSTRAINT fk_idoso_lar
        FOREIGN KEY (id_lar)
        REFERENCES lar(id_lar)
        ON DELETE RESTRICT
);

CREATE TABLE estoque (
    id_estoque int4 GENERATED BY DEFAULT AS IDENTITY,
    id_medicamento int4 NOT NULL,
    qtd_atual int4 NOT NULL,
    qtd_minima int4 NOT NULL,
    lote varchar(50) NOT NULL,
    validade date NOT NULL,

    CONSTRAINT estoque_pkey PRIMARY KEY (id_estoque),

    CONSTRAINT fk_estoque_medicamento
        FOREIGN KEY (id_medicamento)
        REFERENCES medicamento(id_medicamento)
        ON DELETE RESTRICT
);

-- =====================================================================
-- 4. TABELAS DE EVENTOS, HISTÓRICOS E DEPENDENTES
-- =====================================================================

CREATE TABLE responsavel (
    id_responsavel int4 GENERATED BY DEFAULT AS IDENTITY,
    nome_responsavel varchar(255) NOT NULL,
    cpf varchar(30) NOT NULL UNIQUE,
    telefone varchar(20) NOT NULL,
    parentesco varchar(50) NOT NULL,
    id_idoso int4 NOT NULL,

    CONSTRAINT responsavel_pkey PRIMARY KEY (id_responsavel),

    CONSTRAINT fk_responsavel_idoso
        FOREIGN KEY (id_idoso)
        REFERENCES idoso(id_idoso)
        ON DELETE CASCADE
);

CREATE TABLE movimentacao (
    id_movimentacao int4 GENERATED BY DEFAULT AS IDENTITY,
    tipo tipo_movimentacao NOT NULL,
    qtd int4 NOT NULL,
    data_hora timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    obs text,
    id_estoque int4 NOT NULL,
    id_funcionario int4 NOT NULL,

    CONSTRAINT movimentacao_pkey PRIMARY KEY (id_movimentacao),

    CONSTRAINT fk_movimentacao_estoque
        FOREIGN KEY (id_estoque)
        REFERENCES estoque(id_estoque)
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimentacao_funcionario
        FOREIGN KEY (id_funcionario)
        REFERENCES funcionario(id_funcionario)
        ON DELETE RESTRICT
);

CREATE TABLE prescricao (
    id_prescricao int4 GENERATED BY DEFAULT AS IDENTITY,
    id_idoso int4 NOT NULL,
    id_medicamento int4 NOT NULL,
    horario varchar(50) NOT NULL,
    qtd int4 NOT NULL,
    data_inicio date NOT NULL,
    data_fim date,
    obs text,
    id_funcionario int4 NOT NULL,

    CONSTRAINT prescricao_pkey PRIMARY KEY (id_prescricao),

    CONSTRAINT fk_prescricao_idoso
        FOREIGN KEY (id_idoso)
        REFERENCES idoso(id_idoso)
        ON DELETE RESTRICT,

    CONSTRAINT fk_prescricao_medicamento
        FOREIGN KEY (id_medicamento)
        REFERENCES medicamento(id_medicamento)
        ON DELETE RESTRICT,

    CONSTRAINT fk_prescricao_funcionario
        FOREIGN KEY (id_funcionario)
        REFERENCES funcionario(id_funcionario)
        ON DELETE RESTRICT
);

CREATE TABLE checkin (
    id_checkin int4 GENERATED BY DEFAULT AS IDENTITY,
    data timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    pressao varchar(20) NOT NULL,
    temperatura decimal(4,2) NOT NULL,
    saturacao int4 NOT NULL,
    evolucao text,
    id_idoso int4 NOT NULL,
    id_funcionario int4 NOT NULL,

    CONSTRAINT checkin_pkey PRIMARY KEY (id_checkin),

    CONSTRAINT fk_checkin_idoso
        FOREIGN KEY (id_idoso)
        REFERENCES idoso(id_idoso)
        ON DELETE RESTRICT,

    CONSTRAINT fk_checkin_funcionario
        FOREIGN KEY (id_funcionario)
        REFERENCES funcionario(id_funcionario)
        ON DELETE RESTRICT
);

CREATE TABLE consulta (
    id_consulta int4 GENERATED BY DEFAULT AS IDENTITY,
    data date NOT NULL,
    local varchar(255) NOT NULL,
    motivo text NOT NULL,
    especialidade varchar(255) NOT NULL,
    medico varchar(255) NOT NULL,
    obs text,
    id_idoso int4 NOT NULL,
    id_funcionario int4 NOT NULL,

    CONSTRAINT consulta_pkey PRIMARY KEY (id_consulta),

    CONSTRAINT fk_consulta_idoso
        FOREIGN KEY (id_idoso)
        REFERENCES idoso(id_idoso)
        ON DELETE RESTRICT,

    CONSTRAINT fk_consulta_funcionario
        FOREIGN KEY (id_funcionario)
        REFERENCES funcionario(id_funcionario)
        ON DELETE RESTRICT
);